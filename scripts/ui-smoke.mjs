import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { server } from './preview.mjs';

await new Promise(r => server.listen(0, '127.0.0.1', r));
const browser = await chromium.launch({ ...(process.env.ORBIT_CHROMIUM ? { executablePath: process.env.ORBIT_CHROMIUM } : {}), headless: true, args: process.env.ORBIT_CHROMIUM_ARGS ? JSON.parse(process.env.ORBIT_CHROMIUM_ARGS) : [] });
try {
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 } }), errors = [];
  page.on('pageerror', err => errors.push(err.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  const url = `http://127.0.0.1:${server.address().port}/`;
  await page.goto(url);
  await page.getByRole('heading', { name: 'A calmer space for all your accounts.' }).waitFor();
  assert.equal(await page.locator('tr.account-row').count(), 0);
  await page.getByRole('button', { name: 'Explore demo' }).click();
  assert.equal(await page.locator('tr.account-row').count(), 9);
  await mkdir('docs/screenshots', { recursive: true });
  await page.screenshot({ path: 'docs/screenshots/accounts.png' });
  await page.getByRole('textbox', { name: 'Search accounts' }).fill('Atlas_005');
  assert.equal(await page.locator('tr.account-row').count(), 1);
  assert.ok((await page.locator('tr.account-row').textContent()).includes('Needs verification'));
  await page.getByRole('textbox', { name: 'Search accounts' }).fill('');
  await page.getByLabel('Select visible accounts').check();
  assert.equal(await page.locator('[data-select]:checked').count(), 9);
  await page.getByRole('button', { name: 'Clear selection' }).click();
  await page.getByRole('button', { name: 'Add group', exact: true }).click();
  await page.getByRole('textbox', { name: 'Group name' }).fill('My extra group');
  await page.getByRole('button', { name: 'Create group', exact: true }).click();
  await page.getByRole('button', { name: 'My extra group 0' }).waitFor();
  await page.getByRole('button', { name: 'Live view', exact: true }).click();
  await page.getByRole('heading', { name: 'Live view', exact: true }).waitFor();
  assert.equal(await page.locator('.previewcard').count(), 8);
  await page.screenshot({ path: 'docs/screenshots/live-view.png' });
  await page.locator('.previewcard [data-action="remote.open"]').first().click();
  await page.getByRole('heading', { name: /Sample session/ }).waitFor();
  await page.getByRole('button', { name: 'Take control', exact: true }).click();
  await page.getByText('Demo session only. No real game is being controlled.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close session', exact: true }).click();
  await page.getByRole('button', { name: 'Machines', exact: true }).click();
  assert.equal(await page.locator('.cards .card').count(), 4);
  await page.getByRole('button', { name: 'Schedules', exact: true }).click();
  await page.getByRole('button', { name: 'New schedule' }).click();
  await page.getByRole('textbox', { name: 'Schedule name' }).fill('Test session');
  await page.locator('.checklist input').first().check();
  await page.locator('#modal').getByRole('button', { name: 'Create schedule', exact: true }).click();
  await page.getByText('Test session', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Workspace theme').selectOption('light');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  assert.equal(await page.locator('body.light').count(), 1);
  await page.getByRole('button', { name: 'Accounts', exact: true }).click();
  await page.screenshot({ path: 'docs/screenshots/light.png' });
  await page.setViewportSize({ width: 1100, height: 760 });
  assert.equal(await page.evaluate(() => document.body.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.body.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Exit demo', exact: true }).click();
  await page.getByRole('heading', { name: 'A calmer space for all your accounts.' }).waitFor();
  assert.equal(await page.locator('tr.account-row').count(), 0);
  assert.deepEqual(errors, []);
  console.log('UI smoke checks passed: empty state, demo isolation, table/search/selection, groups, live view, remote dialog, machines, schedules, themes, and responsive layout.');
} finally { await browser.close(); server.close(); }
